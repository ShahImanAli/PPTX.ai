
export async function generateAndStoreImage(
  prompt: string,
  filename: string,
): Promise<string> {
  const accountId = process.env.CLOUDFLARE_AI_ACCOUNT_ID
  const apiToken = process.env.CLOUDFLARE_AI_API_KEY

  if (!accountId || !apiToken) {
    throw new Error(
      'Invalid credentials!.',
    )
  }

  // 1. Generate the image with Cloudflare Workers AI (Flux 1 Schnell)
  const model = '@cf/black-forest-labs/flux-1-schnell'
  const res = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${accountId}/ai/run/${model}`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${apiToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ prompt }),
    },
  )

  if (!res.ok) {
    throw new Error(
      `Image generation failed: ${res.status} ${await res.text()}`,
    )
  }

  const result = (await res.json()) as {
    success: boolean
    result?: { image?: string }
    errors?: Array<{ message: string }>
  }

  if (!result.success || !result.result?.image) {
    throw new Error(
      `Image generation failed: ${JSON.stringify(result.errors)}`,
    )
  }

  // Cloudflare returns the image as a base64-encoded string
  const bytes = Buffer.from(result.result.image, 'base64')
  const mediaType = 'image/png'

  // 2. Upload the generated bytes to ImageKit storage (not generation)
  const form = new FormData()
  form.append(
    'file',
    new Blob([bytes], { type: mediaType }),
    `${filename}.png`,
  )
  form.append('fileName', `${filename}.png`)
  form.append('useUniqueFileName', 'false')
  form.append('folder', '/slides')

  const uploadRes = await fetch(
    'https://upload.imagekit.io/api/v1/files/upload',
    {
      method: 'POST',
      headers: {
        Authorization: `Basic ${Buffer.from(
          `${process.env.IMAGEKIT_PRIVATE_KEY}:`,
        ).toString('base64')}`,
      },
      body: form,
    },
  )

  if (!uploadRes.ok) {
    throw new Error(
      `ImageKit upload failed: ${uploadRes.status} ${await uploadRes.text()}`,
    )
  }

  const upload = (await uploadRes.json()) as { url: string }

  // 3. Return the CDN URL with the existing transformation params
  return `${upload.url}?tr=w-1280,h-720`
}